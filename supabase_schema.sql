-- Run this in the Supabase SQL editor before enabling live persistence.
create table if not exists public.sessions (
  id uuid primary key default gen_random_uuid(),
  caregiver_id uuid references auth.users(id),
  child_id uuid references auth.users(id),
  role text not null check (role in ('caregiver', 'child')),
  duration_minutes integer not null check (duration_minutes between 5 and 120),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.session_events (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sessions(id) on delete cascade,
  signal_type text not null check (signal_type in ('touch', 'rhythm', 'gaze', 'camera')),
  signal_value jsonb not null default '{}'::jsonb,
  recorded_at timestamptz not null default now()
);

alter table public.sessions enable row level security;
alter table public.session_events enable row level security;

create policy "authenticated users manage their sessions"
  on public.sessions for all to authenticated
  using (auth.uid() = caregiver_id or auth.uid() = child_id)
  with check (auth.uid() = caregiver_id or auth.uid() = child_id);

create policy "authenticated users manage session events"
  on public.session_events for all to authenticated
  using (exists (
    select 1 from public.sessions
    where sessions.id = session_events.session_id
      and (sessions.caregiver_id = auth.uid() or sessions.child_id = auth.uid())
  ))
  with check (exists (
    select 1 from public.sessions
    where sessions.id = session_events.session_id
      and (sessions.caregiver_id = auth.uid() or sessions.child_id = auth.uid())
  ));
